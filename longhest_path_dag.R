longest_path_dag <- function(start, end, edges) {
  nodes <- sort(unique(c(edges$from, edges$to)))
  dist <- rep(-Inf, max(nodes) + 1)
  prev <- rep(NA, max(nodes) + 1)
  dist[start + 1] <- 0  # adjust for R's 1-indexing
  
  for (u in nodes) {
    outgoing <- subset(edges, from == u)
    for (i in seq_len(nrow(outgoing))) {
      v <- outgoing$to[i]
      w <- outgoing$weight[i]
      if (dist[u + 1] + w > dist[v + 1]) {
        dist[v + 1] <- dist[u + 1] + w
        prev[v + 1] <- u
      }
    }
  }
  
  # reconstruct path
  path <- c()
  current <- end
  while (!is.na(current)) {
    path <- c(current, path)
    current <- prev[current + 1]
  }
  
  cat(dist[end + 1], "\n", paste(path, collapse = " "), "\n")
}

